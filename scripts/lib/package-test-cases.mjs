// The package test projects' cases (test/package-tests/<Package>/), as scripts/package_tests.mjs
// runs them and scripts/check_package_tests.mjs checks them: the RunAll module generated from a
// project's [TestCase] Subs, what expect.json says a case does, how a result is judged against
// it, and the markers that tie each callout of a section's pages to the cases behind it.
// lib/package-tests.mjs puts a project together; test/package-tests/README.md describes it all.

import { EXPECT_FILE, RUNALL_FILE } from "../../lib/package-tests.mjs";
import { findCases } from "./tb-tests.mjs";

export const ARCHES = ["win32", "win64"];

/**
 * The cases of a package's project: its [TestCase] Subs and its compile cases, from the package
 * folder's own sources (Expect.twin and RunAll.twin are not its cases).
 *
 * @param {{name: string, text: string}[]} files  testSources' list
 */
export function projectCases(files) {
  const own = files.filter((f) => f.name !== EXPECT_FILE && f.name !== RUNALL_FILE);
  return findCases(own);
}

const caseName = (t) => `${t.fixture}.${t.name}`;

/**
 * The text of RunAll.twin: Sub Main runs every [TestCase] Sub under Expect's collecting mode and
 * prints PASS, FAIL or SKIP for each. A case expect.json says never returns, or ends in a native
 * exception, is skipped on the architecture where it does (skipReason).
 *
 * @param {object} o
 * @param {string} o.pkg
 * @param {string} o.version  the package's version, as a.b.c.d
 * @param {{fixture: string, name: string}[]} o.tests
 * @param {object} o.expect   expect.json
 */
export function runAllText({ pkg, version, tests, expect }) {
  const lines = [
    "' Generated by scripts/package_tests.mjs from this project's [TestCase] Subs and expect.json:",
    "' do not edit. Run Sub Main: each case prints PASS, FAIL or SKIP in the DEBUG CONSOLE.",
    `' The cases are written for the package ${pkg}, version ${version}. Each one checks what is`,
    "' correct, so a case that fails names a defect of the package.",
    "Module RunAll",
    "",
    "    Public Sub Main()",
    `        Expect.StartRun "${pkg} ${version}: ${tests.length} test case${tests.length === 1 ? "" : "s"}"`,
    "        On Error Resume Next",
  ];
  const run = (name) => [
    "        Expect.StartCase",
    "        Err.Clear",
    `        ${name}`,
    `        Expect.EndCase "${name}", Err.Number, Err.Description`,
  ];
  for (const t of tests) {
    const name = caseName(t);
    const why = Object.fromEntries(ARCHES.map((a) => [a, skipReason(expectationFor(expect, name, a), version)]));
    if (why.win32 && why.win64 && why.win32 === why.win64) {
      lines.push(`        Expect.Skip "${name}", "${why.win32}"`);
    } else if (why.win32 || why.win64) {
      const branch = (a) => (why[a] ? [`        Expect.Skip "${name}", "${why[a]}"`] : run(name));
      lines.push("#If Win64 Then", ...branch("win64"), "#Else", ...branch("win32"), "#End If");
    } else lines.push(...run(name));
  }
  lines.push("        On Error GoTo 0", "        Expect.EndRun", "    End Sub", "", "End Module", "");
  return lines.join("\n");
}

// Why RunAll skips a case on one architecture, or "": one that never returns would stop the run,
// and one that ends in a native exception (a stack overflow, an access violation) may take the
// reader's IDE or exe down with it, as it does a built exe. package_tests.mjs still runs both.
function skipReason(expected, version) {
  if (expected.kind === "hang") return `it does not return in version ${version}`;
  if (expected.kind === "fail" && /NATIVE EXCEPTION/.test(expected.detail))
    return `it ends in a native exception in version ${version}`;
  return "";
}

/**
 * What expect.json says a case does on one architecture. A case it does not name passes. An
 * entry is { fails: "<detail>" } or { hangs: true }, for both architectures, or
 * { win32: <one>, win64: <one> }, where <one> is "pass" or one of those two.
 *
 * @returns {{kind: "pass" | "fail" | "hang", detail: string}}
 */
export function expectationFor(expect, name, arch) {
  let e = expect?.cases?.[name];
  if (e && (e.win32 !== undefined || e.win64 !== undefined)) e = e[arch];
  if (!e || e === "pass") return { kind: "pass", detail: "" };
  if (e.hangs) return { kind: "hang", detail: "" };
  if (typeof e.fails === "string") return { kind: "fail", detail: e.fails };
  throw new Error(`expect.json: ${name} has an entry that is not pass, fails or hangs`);
}

/** A failure as tbrun reports it, without what changes from run to run: its line and the assertion prefix. */
export function normaliseDetail(detail) {
  return String(detail)
    .replace(/ \(line -?\d+\)$/, "")
    .replace(/^ASSERTION FAILED:\s*/, "")
    .replace(/\s+/g, " ")
    .trim();
}

const NO_ANSWER_RE = /^no answer from the compiler after /;

/** A tbrun case result as one of pass, fail and hang. */
export function outcomeOf(result) {
  if (result.pass) return { kind: "pass", detail: "" };
  if (NO_ANSWER_RE.test(result.detail)) return { kind: "hang", detail: "" };
  return { kind: "fail", detail: normaliseDetail(result.detail) };
}

/**
 * Judges a case's outcome against its expectation.
 *
 * @returns {"documented" | "fixed" | "changed"}  documented: as expect.json says; fixed: it was
 *   expected to fail or hang and passes; changed: anything else
 */
export function judge(expected, outcome) {
  if (expected.kind === outcome.kind) {
    if (expected.kind !== "fail" || normaliseDetail(expected.detail) === outcome.detail) return "documented";
    return "changed";
  }
  return outcome.kind === "pass" ? "fixed" : "changed";
}

/**
 * expect.json as a run's outcomes give it. `outcomes` maps a case name to { win32, win64 }
 * outcomes; an architecture not run keeps what `previous` says.
 */
export function expectFrom({ version, names, outcomes, previous }) {
  const one = (o) => (o.kind === "pass" ? "pass" : o.kind === "hang" ? { hangs: true } : { fails: o.detail });
  const cases = {};
  for (const name of names) {
    const per = {};
    for (const a of ARCHES) {
      const o = outcomes.get(name)?.[a] ?? expectationFor(previous, name, a);
      per[a] = one(o);
    }
    const same = JSON.stringify(per.win32) === JSON.stringify(per.win64);
    if (same && per.win32 === "pass") continue;
    cases[name] = same ? per.win32 : per;
  }
  return { version, cases };
}

// ---------------------------------------------------------------- markers

// A callout: a blockquote line `> [!NOTE]` or `> [!WARNING]`, indented or not.
const CALLOUT_RE = /^[ \t]*>[ \t]*\[!(NOTE|WARNING)\]/;
// A marker, `<!-- test: <item>, <item> -->`, on a line of its own; and the end of a region.
const MARKER_RE = /^[ \t]*<!--[ \t]*test:[ \t]*(.*?)[ \t]*-->[ \t]*$/;
const END_RE = /^[ \t]*<!--[ \t]*\/test[ \t]*-->[ \t]*$/;
const FENCE_RE = /^[ \t]*(`{3,}|~{3,})/;

/**
 * The markers of a page, outside code fences. A marker on the line directly above a callout
 * marks that callout. Any other marker opens a region, which `<!-- /test -->` closes: the
 * paragraphs, lists, tables and samples between them state what the region's cases check.
 * Regions do not nest, and a callout inside one is marked by it.
 *
 * @returns {{callouts: {line: number, kind: string, marked: boolean}[],
 *            markers: {line: number, items: object[]}[], problems: string[]}}  `markers` holds
 *   every marker, a callout's and a region's alike; `items` parses one: { case: "Fixture.Sub" },
 *   { compile: "Name" }, { probe: "id" } or { none: "reason" }, and { bad: "text" } for one it
 *   cannot read. `problems` names a region not closed, a region opened inside another and a
 *   close with no region.
 */
export function markersOf(text) {
  const lines = text.split(/\r?\n/);
  const callouts = [];
  const markers = [];
  const problems = [];
  let fence = null;
  let open = null; // the line of the region's marker
  for (let i = 0; i < lines.length; i++) {
    const f = FENCE_RE.exec(lines[i]);
    if (f) {
      if (!fence) fence = f[1][0];
      else if (f[1][0] === fence) fence = null;
      continue;
    }
    if (fence) continue;
    const m = MARKER_RE.exec(lines[i]);
    if (m) {
      markers.push({ line: i + 1, items: parseMarker(m[1]) });
      if (CALLOUT_RE.test(lines[i + 1] ?? "")) continue; // a callout's own marker
      if (open !== null) problems.push(`line ${i + 1}: a region opens inside the region of line ${open}`);
      open = i + 1;
      continue;
    }
    if (END_RE.test(lines[i])) {
      if (open === null) problems.push(`line ${i + 1}: <!-- /test --> closes no region`);
      open = null;
      continue;
    }
    const c = CALLOUT_RE.exec(lines[i]);
    if (c) callouts.push({ line: i + 1, kind: c[1], marked: open !== null || MARKER_RE.test(lines[i - 1] ?? "") });
  }
  if (open !== null) problems.push(`line ${open}: the region is not closed with <!-- /test -->`);
  return { callouts, markers, problems };
}

/** The items of a marker: Fixture.Sub, compile <Name>, probe <id>, none -- <reason>. */
export function parseMarker(text) {
  const none = /^none[ \t]*(?:--|:)?[ \t]*(.*)$/.exec(text);
  if (none) return [none[1].trim() ? { none: none[1].trim() } : { bad: "none needs a reason" }];
  return text
    .split(",")
    .map((s) => s.trim())
    .filter(Boolean)
    .map((s) => {
      let m = /^(\w+)\.(\w+)$/.exec(s);
      if (m) return { case: s };
      m = /^compile[ \t]+(\w+)$/.exec(s);
      if (m) return { compile: m[1] };
      m = /^probe[ \t]+([\w,.-]+)$/.exec(s);
      if (m) return { probe: m[1] };
      return { bad: s };
    });
}

/**
 * The [TestCase] Subs whose first statement is not Expect.Begin or whose last is not
 * Expect.Done.
 *
 * @param {{name: string, text: string}[]} files
 * @returns {string[]}  one line for each
 */
export function malformedCases(files, tests) {
  const out = [];
  for (const t of tests) {
    const file = files.find((f) => f.name === t.file);
    const lines = file.text.split(/\r?\n/);
    const body = [];
    for (let i = t.line; i < lines.length; i++) {
      if (/^[ \t]*End[ \t]+Sub\b/i.test(lines[i])) break;
      const s = lines[i].replace(/'.*$/, "").trim();
      if (s) body.push(s);
    }
    if (!/^Expect\.Begin$/i.test(body[0] ?? ""))
      out.push(`${t.file} line ${t.line}: ${caseName(t)} does not start with Expect.Begin`);
    if (!/^Expect\.Done$/i.test(body.at(-1) ?? ""))
      out.push(`${t.file} line ${t.line}: ${caseName(t)} does not end with Expect.Done`);
  }
  return out;
}
