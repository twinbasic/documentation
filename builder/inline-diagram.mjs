// A diagram's SVG made ready to be inlined into a page (render.mjs, figurePlugin).
//
// Graphviz writes a <title> into every node, edge and cluster, holding its DOT identifier
// (`w1`, `cluster_form`, `CF->HI`): a pointer shows it as a tooltip, and the search index
// reads it as the page's text. An inlined Graphviz diagram drops them; the .svg file keeps
// them. An SVG Graphviz did not write keeps its titles.
//
// A diagram whose boxes link somewhere (URL attributes in its DOT) is inlined as a group
// of links, and takes two more changes:
// - `<a xlink:href>` becomes `<a href>`, the attribute the link check reads and figure.js
//   finds a link by. The offline and book rewrites read either.
// - Each cluster is moved to just before the first node inside it. Graphviz emits every
//   cluster ahead of every node, so a reader, and the Tab key, would meet all the group
//   labels first and their boxes after. The nodes keep Graphviz's order, which is the
//   order the DOT declares them in when it sets `outputorder=nodesfirst`: a DOT whose
//   boxes link declares them in reading order and sets it.

const GRAPHVIZ_MARK = "<!-- Generated by graphviz";
const CLUSTER_OR_NODE_RE = /<g id="[^"]*" class="(cluster|node)">/g;
const G_TAG_RE = /<g[\s>]|<\/g>/g;
const POINT_RE = /(-?\d+(?:\.\d+)?),(-?\d+(?:\.\d+)?)/g;
const TEXT_AT_RE = /<text\b[^>]*?\bx="(-?[\d.]+)" y="(-?[\d.]+)"/;
const TITLE_RE = /<title>[^<]*<\/title>\r?\n?/g;
const XLINK_HREF_RE = /<a xlink:href=/g;

// The SVG to inline, and whether it is a group of links.
export function inlineDiagram(svg) {
  if (!svg.startsWith(GRAPHVIZ_MARK)) return { svg, linked: false };
  const linked = svg.includes("<a xlink:href=");
  if (linked) svg = clustersBeforeTheirNodes(svg.replace(XLINK_HREF_RE, "<a href="));
  return { svg: svg.replace(TITLE_RE, ""), linked };
}

// The top-level cluster and node groups, each with where it starts and ends; a cluster
// with its box, a node with the point its label is drawn at (none for a node with no
// label).
function clusterAndNodeBlocks(svg) {
  const blocks = [];
  CLUSTER_OR_NODE_RE.lastIndex = 0;
  for (let m = CLUSTER_OR_NODE_RE.exec(svg); m; m = CLUSTER_OR_NODE_RE.exec(svg)) {
    let depth = 0;
    G_TAG_RE.lastIndex = m.index;
    let end = -1;
    for (let t = G_TAG_RE.exec(svg); t; t = G_TAG_RE.exec(svg)) {
      depth += t[0] === "</g>" ? -1 : 1;
      if (depth === 0) {
        end = G_TAG_RE.lastIndex;
        break;
      }
    }
    if (end < 0) break;
    const text = svg.slice(m.index, end);
    const block = { kind: m[1], start: m.index, end, text };
    if (block.kind === "cluster") block.box = boxOf(text);
    else {
      const at = TEXT_AT_RE.exec(text);
      block.at = at ? [Number(at[1]), Number(at[2])] : null;
    }
    blocks.push(block);
    CLUSTER_OR_NODE_RE.lastIndex = end;
  }
  return blocks;
}

// The bounding box of the first shape in a cluster's group: its outline.
function boxOf(text) {
  const shape = /\s(?:d|points)="([^"]*)"/.exec(text);
  const xs = [];
  const ys = [];
  for (const [, x, y] of shape?.[1].matchAll(POINT_RE) ?? []) {
    xs.push(Number(x));
    ys.push(Number(y));
  }
  if (xs.length === 0) return null;
  return { x0: Math.min(...xs), x1: Math.max(...xs), y0: Math.min(...ys), y1: Math.max(...ys) };
}

const inside = (box, [x, y]) => box && x >= box.x0 && x <= box.x1 && y >= box.y0 && y <= box.y1;
const area = (box) => (box.x1 - box.x0) * (box.y1 - box.y0);

function clustersBeforeTheirNodes(svg) {
  const blocks = clusterAndNodeBlocks(svg);
  const clusters = blocks.filter((b) => b.kind === "cluster");
  const nodes = blocks.filter((b) => b.kind === "node");
  if (clusters.length === 0 || nodes.length === 0) return svg;

  // Each cluster goes before the first node inside it, an outer cluster before an inner
  // one; a cluster with no node inside it stays where it is.
  const before = new Map();
  for (const c of clusters) {
    const first = nodes.find((n) => n.at && inside(c.box, n.at));
    if (!first) continue;
    if (!before.has(first)) before.set(first, []);
    before.get(first).push(c);
    c.moved = true;
  }
  for (const list of before.values()) list.sort((a, b) => area(b.box) - area(a.box));

  // Rebuilt from the pieces between the blocks: a moved cluster leaves its place empty
  // (with the line break after it), and lands at the start of its first node's place.
  let out = "";
  let pos = 0;
  for (const b of blocks) {
    out += svg.slice(pos, b.start);
    if (b.kind === "node") for (const c of before.get(b) ?? []) out += `${c.text}\n`;
    if (b.moved) {
      pos = b.end + (/^\r?\n/.exec(svg.slice(b.end, b.end + 2))?.[0].length ?? 0);
      continue;
    }
    out += b.text;
    pos = b.end;
  }
  return out + svg.slice(pos);
}
